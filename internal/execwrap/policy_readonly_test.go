package execwrap

import "testing"

func TestReadOnly(t *testing.T) {
	cases := []struct {
		command string
		want    bool
	}{
		// Read-only, one command, no metacharacter.
		{"git status", true},
		{"  git status --short  ", true},
		{"git log --oneline -n 5", true},
		{"git diff --stat", true},
		{"git show HEAD", true},
		{"git branch", true},
		{"git branch -a -v", true},
		{"git branch --show-current", true},
		{"git rev-parse HEAD", true},
		{"git ls-files", true},
		{"git remote -v", true},
		{"git stash list", true},
		{"gh pr view 12", true},
		{"gh pr list", true},
		{"gh pr checks 12", true},
		{"gh issue list", true},
		{"gh run view 99", true},
		{"gh repo view", true},
		{"go version", true},
		{"go env GOPATH", true},
		{"go list ./...", true},
		{"go doc fmt.Println", true},
		{"mise list", true},
		{"asdf current", true},
		{"direnv status", true},
		{"ls -la internal", true},
		{"wc -l main.go", true},
		{"wc -l a.go b.go", true},
		{"find . -type f -maxdepth 2", true},
		{"grep -rn func internal", true},
		{"grep -rl foo internal", true},
		{"rg -n func internal", true},
		{"rg --files internal", true},
		{"cat main.go", true},
		{"head -n 40 main.go", true},
		{"tail -40 main.go", true},
		{"sed -n 10,20p main.go", true},
		{"jq . package.json", true},
		{"git fetch origin", true},
		{"git fetch --all --tags", true},
		{"agent-desktop snapshot --app Files -i", true},
		{"agent-desktop find --role button --name Save", true},

		// Chained or with any shell metacharacter.
		{"go version ; perl /tmp/x.pl", false},
		{"git status && rm -rf x", false},
		{"git status || true", false},
		{"git status | cat", false},
		{"git status &", false},
		{"git status $(id)", false},
		{"git status `id`", false},
		{"git status > out", false},
		{"git status < in", false},
		{"git status\nperl x", false},
		{"git status\tx", false},
		{"cd sub && git status", false},

		// Env assignments can redirect a program to run code.
		{"GIT_EXTERNAL_DIFF=/tmp/x git diff", false},

		// Runners, builds, tests and installs execute project code.
		{"make check", false},
		{"go test ./...", false},
		{"go run .", false},
		{"go build ./...", false},
		{"go generate ./...", false},
		{"uv run pytest", false},
		{"npm test", false},
		{"pytest", false},
		{"cargo test", false},

		// Mutating subcommands and flags.
		{"git pull", false},
		{"git commit -m x", false},
		{"git branch -D main", false},
		{"git branch new", false},
		{"git stash", false},
		{"git stash pop", false},
		{"git remote add x y", false},
		{"git diff --output=/tmp/x", false},
		{"git diff --ext-diff", false},
		{"git log --textconv", false},
		{"git checkout main", false},
		{"gh pr merge 12", false},
		{"gh pr checkout 12", false},
		{"gh issue close 3", false},
		{"gh run rerun 99", false},
		{"gh api repos/x/y", false},
		{"gh auth status", false},
		{"gh repo delete x", false},
		{"go env -w GOFLAGS=-x", false},
		{"go env -u GOFLAGS", false},
		{"go list -toolexec=/tmp/x ./...", false},
		{"go list --toolexec /tmp/x ./...", false},
		{"go list -mod=mod ./...", false},
		{"mise use node@20", false},
		{"mise install", false},
		{"asdf global node 20", false},
		{"direnv allow", false},
		{"aws s3 cp a b", false},
		{"kubectl get pods", false},

		// Security review of the read-only set.
		{"go tool compile -o x.o m.go", false},
		{"go tool mytool", false},
		{"go tool pprof -http=:8080 x", false},
		{"go doc -http", false},
		{"go doc --http=:6060", false},
		{"git stash list --output=/tmp/x", false},
		{"git stash list -p --ext-diff", false},
		{"git stash list -p", true},
		{"gh repo view --web", false},
		{"gh pr view 1 -w", false},
		{"gh search repos x --web", false},
		{"gh search repos x", true},
		{"agent-desktop click @s1:e3", false},
		{"agent-desktop snapshot --debug", false},
		{"agent-desktop snapshot --screenshot out.png", false},

		// Unsafe / mutating forms of added read-only families stay false.
		{"find . -delete", false},
		{"find . -exec rm {} ;", false},
		{"find . -execdir sh -c x ;", false},
		{"find . -ok rm ;", false},
		{"find . -fprint out.txt", false},
		{"cat -n main.go", true},
		{"git -C dir status", true},
		{"git -C dir push", false},
		{"git -C dir branch -D main", false},
		{"cat a.go b.go", false},
		{"cat /dev/zero", false},
		{"tail -f app.log", false},
		{"sed -i s/a/b/ main.go", false},
		{"jq .a package.json", false},
		{"wc -c main.go", false},
		{"grep -rn", false},
		{"rg -n --pre cat foo internal", false},
		{"git -c core.pager=evil fetch origin", false},
		{"git fetch --upload-pack=/tmp/evil origin", false},
		{"git fetch --upload-pack /tmp/evil origin", false},
		{"git fetch -f origin", false},
		{"git fetch --force origin", false},
		{"git fetch -p origin", false},
		{"git fetch --prune origin", false},
		{"git fetch -ap origin", false},
		{"git fetch -u origin", false},
		{"git fetch --update-head-ok origin", false},
		{"git fetch origin main:evil", false},
		{"git fetch ext::evil", false},

		// git -C <dir> with read-only vs mutating forms.
		{"git -C repo status --short", true},
		{"git -C repo log -n 5", true},
		{"git -C repo diff --stat", true},
		{"git -C repo show HEAD", true},
		{"git -C repo branch", true},
		{"git -C repo branch -a", true},
		{"git -C repo branch -a -v", true},
		{"git -C repo branch -av", true},
		{"git -C repo branch --show-current", true},
		{"git -C repo remote -v", true},
		{"git -C repo remote get-url origin", true},
		{"git -C repo stash list", true},
		{"git -C repo stash show --stat", true},
		{"git -C repo rev-parse HEAD", true},
		{"git -C repo ls-files", true},
		{"git -C repo fetch origin", true},
		{"git -C a -C b status", true},
		{"git -C repo diff --output=/tmp/x", false},
		{"git -C repo diff --ext-diff", false},
		{"git -C repo log --textconv", false},
		{"git -C repo branch new", false},
		{"git -C repo remote add x y", false},
		{"git -C repo stash", false},
		{"git -C repo stash pop", false},
		{"git -C repo stash list --output=/tmp/x", false},
		{"git -C repo stash show --ext-diff", false},
		{"git -C repo fetch --force origin", false},
		{"git -C repo fetch origin main:evil", false},
		{"git -C repo -c core.pager=evil status", false},

		// git tag (list-only vs creating/deleting/signing).
		{"git tag", true},
		{"git tag -l", true},
		{"git tag --list", true},
		{"git tag -l v1", true},
		{"git tag --list v0.24", true},
		{"git tag -n", true},
		{"git tag -n5", true},
		{"git tag --sort=-v:refname", true},
		{"git tag --sort -v:refname", true},
		{"git tag --contains HEAD", true},
		{"git tag --merged main", true},
		{"git tag --merged=main", true},
		{"git tag --points-at HEAD", true},
		{"git -C repo tag -l --sort=-v:refname", true},
		{"git tag v1.0", false},
		{"git tag v1.0 HEAD", false},
		{"git tag -a v1.0 -m msg", false},
		{"git tag -d v1.0", false},
		{"git tag --delete v1.0", false},
		{"git tag -f v1.0", false},
		{"git tag -s v1.0", false},
		{"git tag -l -d v1.0", false},
		{"git tag --sort=-v:refname v1.0", false},
		{"git tag --sort --delete v1.0", false},
		{"git tag --merged main v1.0", false},
		{"git -C repo tag v1.0", false},

		// git config (read-only flags vs write/edit/file flags).
		{"git config --list", true},
		{"git config -l", true},
		{"git config --list --show-origin --show-scope", true},
		{"git config --global --get user.name", true},
		{"git config --local --get-all remote.origin.fetch", true},
		{"git config --get-regexp alias", true},
		{"git config --get --default=main init.defaultBranch", true},
		{"git -C repo config --list", true},
		{"git config user.name", false},
		{"git config user.name foo", false},
		{"git config --set user.name foo", false},
		{"git config --unset user.name", false},
		{"git config --list --edit", false},
		{"git config -l -e", false},
		{"git config --get user.name --add foo bar", false},
		{"git config --file /etc/passwd --list", false},
		{"git -C repo config --list --edit", false},

		// git grep (read-only vs pager/textconv execution).
		{"git grep -n func", true},
		{"git grep -ni func internal", true},
		{"git grep func internal", true},
		{"git grep -l func", true},
		{"git -C repo grep -n func", true},
		{"git grep -n -O vim func", false},
		{"git grep -Ovim func", false},
		{"git grep -nO func", false},
		{"git grep --open-files-in-pager=vim func", false},
		{"git grep --open-files-in-pager vim func", false},
		{"git grep -n --textconv func", false},

		// Other read-only git subcommands and remote/stash reads.
		{"git describe --tags --always", true},
		{"git rev-list --count HEAD", true},
		{"git merge-base main HEAD", true},
		{"git ls-tree --name-only HEAD", true},
		{"git show-ref --heads", true},
		{"git for-each-ref", true},
		{"git remote get-url origin", true},
		{"git stash show -p", true},
		{"git symbolic-ref HEAD refs/heads/evil", false},

		// Bare single-word read-only listings and Docker/glab reads.
		{"ls", true},
		{"/bin/ls", true},
		{"find", true},
		{"docker ps", true},
		{"docker ps -a", true},
		{"docker images", true},
		{"docker logs mycontainer", true},
		{"docker logs --tail 50 mycontainer", true},
		{"docker logs -f mycontainer", false},
		{"docker logs --follow mycontainer", false},
		{"docker build .", false},
		{"docker run alpine", false},
		{"docker exec c1 ls", false},
		{"docker exec -e GIT_EXTERNAL_DIFF=/tmp/x c1 git diff", false},
		{"docker compose exec web git status", false},
		{"docker-compose exec web git status", false},
		{"glab mr list", true},
		{"glab issue view 42", true},
		{"glab mr view 42 --web", false},

		// Edge shapes.
		{"", false},
		{"git", false},
		{"downshift compact -- git status", false},
	}
	for _, c := range cases {
		t.Run(c.command, func(t *testing.T) {
			if got := ReadOnly(c.command); got != c.want {
				t.Fatalf("ReadOnly(%q) = %v, want %v", c.command, got, c.want)
			}
		})
	}
}
